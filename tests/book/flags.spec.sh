#!/usr/bin/env bash
# Spec: every [FLAG: ...] in the sources is surfaced at the top of the book.
# The book is a view of .brand/, so every value it renders must come from the
# canonical files. Prints TAP. Run from the repo root: bash tests/book/flags.spec.sh
cd "$(dirname "$0")/../.." || exit 1
BOOK=.brand/book.html
fails=0
ok()  { echo "ok - $1"; }
nok() { echo "not ok - $1"; fails=$((fails+1)); }
[ -f "$BOOK" ] || { echo "unevaluable: no $BOOK here; the book is generated by /petals book into the ignored brand cache"; exit 3; }

# 5. every [FLAG: ...] in the sources appears in the book before its first section
first=$(grep -nE '<section' "$BOOK" | head -1 | cut -d: -f1); first=${first:-999999}
missing=0; total=0
while IFS= read -r flag; do
  total=$((total+1))
  line=$(grep -nF -- "$flag" "$BOOK" | head -1 | cut -d: -f1)
  { [ -n "$line" ] && [ "$line" -lt "$first" ]; } || missing=$((missing+1))
done < <(grep -rhoE '\[FLAG: [^]]+\]' .brand/*.md .brand/products/*/*.md 2>/dev/null | sed -E 's/^\[FLAG: //; s/\]$//')
if [ "$missing" -eq 0 ]; then ok "all $total source flags are surfaced before the first section"; else nok "$missing of $total source flags are missing from the top of the book"; fi

echo; echo "$fails failure(s)"; exit "$fails"

echo; echo "$fails failure(s)"; exit "$fails"
