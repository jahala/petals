#!/usr/bin/env bash
# Spec: the book's --pp-* colours equal colors.md.
# The book is a view of .brand/, so every value it renders must come from the
# canonical files. Prints TAP. Run from the repo root: bash tests/book/colors.spec.sh
cd "$(dirname "$0")/../.." || exit 1
BOOK=.brand/book.html
fails=0
ok()  { echo "ok - $1"; }
nok() { echo "not ok - $1"; fails=$((fails+1)); }
[ -f "$BOOK" ] || { echo "unevaluable: no $BOOK here; the book is generated by /petals book into the ignored brand cache"; exit 3; }

# 1. every --pp-* custom property in the book equals colors.md's value for that name
mism=""; n=0
while IFS=: read -r name val; do
  n=$((n+1))
  # a property colors.md declares must carry the declared value; any other
  # property must use a hex colors.md documents somewhere (its tables)
  want=$(grep -hoE -- "$name:[[:space:]]*#[0-9A-Fa-f]{3,8}" .brand/colors.md .brand/products/*/colors.md 2>/dev/null | head -1 | grep -oE '#[0-9A-Fa-f]{3,8}')
  if [ -n "$want" ]; then
    [ "$(echo "$want" | tr a-f A-F)" = "$(echo "$val" | tr a-f A-F)" ] || mism="$mism $name=$val(declared $want)"
  else
    grep -qiF -- "$val" .brand/colors.md .brand/products/*/colors.md 2>/dev/null || mism="$mism $name=$val(not in colors.md)"
  fi
done < <(grep -oE -- '--pp-[a-z0-9-]+:\s*#[0-9A-Fa-f]{3,8}' "$BOOK" | sed -E 's/:[[:space:]]*/:/')
if [ "$n" -gt 0 ] && [ -z "$mism" ]; then ok "all $n --pp-* colours in the book match colors.md"; else nok "book colours match colors.md:${mism:- none found}"; fi

echo; echo "$fails failure(s)"; exit "$fails"
