#!/usr/bin/env bash
# Spec: the book's font import and font roles equal typography.md.
# The book is a view of .brand/, so every value it renders must come from the
# canonical files. Prints TAP. Run from the repo root: bash tests/book/fonts.spec.sh
cd "$(dirname "$0")/../.." || exit 1
BOOK=.brand/book.html
fails=0
ok()  { echo "ok - $1"; }
nok() { echo "not ok - $1"; fails=$((fails+1)); }
[ -f "$BOOK" ] || { echo "unevaluable: no $BOOK here; the book is generated by /petals book into the ignored brand cache"; exit 3; }

# 2. the Google Fonts URL in the book is the one typography.md documents
want_url=$(grep -oE 'https://fonts.googleapis.com/css2\?[^"'"'"')]+' .brand/typography.md | head -1)
got_url=$(grep -oE 'https://fonts.googleapis.com/css2\?[^"'"'"')]+' "$BOOK" | head -1)
if [ -n "$want_url" ] && [ "$want_url" = "$got_url" ]; then ok "font import URL matches typography.md"; else nok "font import URL matches typography.md (book: ${got_url:-none})"; fi

# 3. --font-heading / --font-body / --font-code equal typography.md's declarations
for role in heading body code; do
  w=$(grep -oE -- "--font-$role:[^;]+" .brand/typography.md | head -1)
  g=$(grep -oE -- "--font-$role:[^;]+" "$BOOK" | head -1)
  if [ -n "$w" ] && [ "$w" = "$g" ]; then ok "--font-$role matches typography.md"; else nok "--font-$role matches typography.md (book: ${g:-none}, want: ${w:-none})"; fi
done

echo; echo "$fails failure(s)"; exit "$fails"
