#!/usr/bin/env bash
# Spec: the book carries a current source fingerprint.
# The book is a view of .brand/, so every value it renders must come from the
# canonical files. Prints TAP. Run from the repo root: bash tests/book/fingerprint.spec.sh
cd "$(dirname "$0")/../.." || exit 1
BOOK=.brand/book.html
fails=0
ok()  { echo "ok - $1"; }
nok() { echo "not ok - $1"; fails=$((fails+1)); }
[ -f "$BOOK" ] || { echo "unevaluable: no $BOOK here; the book is generated by /petals book into the ignored brand cache"; exit 3; }

# 4. the book carries a source fingerprint equal to sha256 over the canonical sources
fp=$(grep -oE 'name="source-fingerprint" content="sha256:[0-9a-f]{64}"' "$BOOK" | grep -oE '[0-9a-f]{64}')
want_fp=$(cat .brand/colors.md .brand/typography.md .brand/voice.md .brand/identity.md .brand/layout.md .brand/components.md .brand/products/*/*.md 2>/dev/null | shasum -a 256 | cut -d' ' -f1)
if [ -z "$fp" ]; then nok "book carries a source-fingerprint meta tag (none found)"
elif [ "$fp" = "$want_fp" ]; then ok "source fingerprint matches the canonical sources"
else nok "source fingerprint matches the canonical sources (book is stale)"; fi

echo; echo "$fails failure(s)"; exit "$fails"
